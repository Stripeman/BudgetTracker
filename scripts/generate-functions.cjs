'use strict';
// Generates api/<route>/function.json and index.js from api/_shared/routes.js so the Azure
// Functions bindings can never drift from the registry. Run: node scripts/generate-functions.cjs
const fs = require('node:fs');
const path = require('node:path');
const { ROUTES } = require('../api/_shared/routes.js');

const API = path.join(__dirname, '..', 'api');
for (const [name, def] of Object.entries(ROUTES)) {
  const dir = path.join(API, name);
  fs.mkdirSync(dir, { recursive: true });
  const fn = {
    bindings: [
      { authLevel: 'anonymous', type: 'httpTrigger', direction: 'in', name: 'req', methods: def.methods.map((m) => m.toLowerCase()), route: name },
      { type: 'http', direction: 'out', name: 'res' },
    ],
  };
  fs.writeFileSync(path.join(dir, 'function.json'), `${JSON.stringify(fn, null, 2)}\n`);
  const opts = def.options ? `, ${JSON.stringify(def.options)}` : '';
  fs.writeFileSync(path.join(dir, 'index.js'),
    `'use strict';\n// Generated by scripts/generate-functions.cjs from api/_shared/routes.js. Do not edit.\nmodule.exports = require('../_shared/runtime').route(require('./handler')${opts});\n`);
}
console.log(`generated ${Object.keys(ROUTES).length} functions`);
